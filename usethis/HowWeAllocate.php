        <li><strong>Time spent</strong>: logged hours for non-code work</li>
        <li><strong>Ops & Support</strong>: tickets resolved, server work</li>
        <li><strong>QA & Testing</strong>: verified bug reports, test sessions</li>
        <li><strong>Impact</strong>: leadership, release coordination, big wins</li>
      </ul>
      <p class="muted">Weights and results are published each quarter for fairness and clarity.</p>
